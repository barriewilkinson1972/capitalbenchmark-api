#!/usr/bin/env python3
"""
Render stored Capital Benchmark credit memo payloads to DOCX and/or PDF.

This script reads stored memo JSON files generated by:
    run_credit_memo_generation_grid_20_names.py

It makes zero OpenAI calls.

Expected input:
    benchmark_runs/benchmark_20_mini_memos/raw_memos/*.json

Default output:
    benchmark_runs/benchmark_20_mini_memos/rendered_files/
      docx/
      pdf/
      render_summary.csv

Example:
    python render_stored_credit_memos.py \
        --memo-dir benchmark_runs/benchmark_20_mini_memos/raw_memos \
        --formats both

If running outside the production project root, pass the renderer module path:
    python render_stored_credit_memos.py \
        --memo-dir benchmark_runs/benchmark_20_mini_memos/raw_memos \
        --renderer-module /opt/capitalbenchmark-api/model/credit_memo_documents.py \
        --formats both

PDF generation requires LibreOffice. On Ubuntu:
    sudo apt install -y libreoffice
"""

from __future__ import annotations

import argparse
import csv
import importlib.util
import json
import os
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Callable


RenderDocxFn = Callable[[dict[str, Any], str | Path], Path]
ConvertPdfFn = Callable[[str | Path, str | Path | None], Path]


def load_renderer(renderer_module_path: str | None = None) -> tuple[RenderDocxFn, ConvertPdfFn]:
    """
    Load render_credit_memo_docx and convert_docx_to_pdf.

    Preferred production import:
        from model.credit_memo_documents import render_credit_memo_docx, convert_docx_to_pdf

    Optional standalone import:
        --renderer-module /path/to/credit_memo_documents.py
    """
    if renderer_module_path:
        module_path = Path(renderer_module_path)
        if not module_path.exists():
            raise FileNotFoundError(f"Renderer module not found: {module_path}")

        # Add the module's parent to sys.path so sibling imports can resolve.
        sys.path.insert(0, str(module_path.parent))

        spec = importlib.util.spec_from_file_location("credit_memo_documents_dynamic", module_path)
        if spec is None or spec.loader is None:
            raise ImportError(f"Could not load module spec from: {module_path}")

        module = importlib.util.module_from_spec(spec)
        sys.modules["credit_memo_documents_dynamic"] = module
        spec.loader.exec_module(module)

        render_credit_memo_docx = getattr(module, "render_credit_memo_docx", None)
        convert_docx_to_pdf = getattr(module, "convert_docx_to_pdf", None)
        if not callable(render_credit_memo_docx):
            raise AttributeError(f"{module_path} does not define render_credit_memo_docx(memo_payload, output_path)")
        if not callable(convert_docx_to_pdf):
            raise AttributeError(f"{module_path} does not define convert_docx_to_pdf(docx_path, output_dir)")
        return render_credit_memo_docx, convert_docx_to_pdf

    try:
        from model.credit_memo_documents import render_credit_memo_docx, convert_docx_to_pdf
        return render_credit_memo_docx, convert_docx_to_pdf
    except Exception as exc:
        raise ImportError(
            "Could not import model.credit_memo_documents. "
            "Run from the project root or pass --renderer-module /path/to/credit_memo_documents.py"
        ) from exc


def safe_filename(value: str) -> str:
    keep: list[str] = []
    for char in str(value):
        if char.isalnum() or char in {"-", "_", "."}:
            keep.append(char)
        else:
            keep.append("_")
    return "".join(keep).strip("_")


def discover_memo_files(memo_dir: Path, pattern: str, recursive: bool) -> list[Path]:
    return sorted(memo_dir.rglob(pattern) if recursive else memo_dir.glob(pattern))


def load_memo_payload(path: Path) -> dict[str, Any]:
    """
    Accept either:
    - a raw /credit_memo response
    - a raw /credit_memo_annotation response containing memo_payload
    """
    payload = json.loads(path.read_text(encoding="utf-8"))
    if isinstance(payload, dict) and isinstance(payload.get("memo_payload"), dict):
        return payload["memo_payload"]
    if isinstance(payload, dict):
        return payload
    raise ValueError(f"JSON file is not an object: {path}")


def get_nested(payload: dict[str, Any], path: list[str], default: Any = None) -> Any:
    current: Any = payload
    for key in path:
        if not isinstance(current, dict):
            return default
        current = current.get(key)
        if current is None:
            return default
    return current


def stable_output_stem(memo_file: Path, memo_payload: dict[str, Any], prefix: str) -> str:
    """
    Preserve the benchmark run identity from the input filename.

    This is better than using timestamped credit_memo_filename(), because
    repeated renders of the same stored memo should overwrite predictably
    or be resumable.
    """
    original_stem = memo_file.stem
    symbol = get_nested(memo_payload, ["memo_context", "borrower", "symbol"], "")
    company = get_nested(memo_payload, ["memo_context", "borrower", "company_name"], "")
    if original_stem:
        return safe_filename(original_stem)

    fallback = f"{prefix}_{symbol}_{company}".strip("_")
    return safe_filename(fallback or f"{prefix}_memo")


def write_summary_csv(path: Path, rows: list[dict[str, Any]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if not rows:
        path.write_text("", encoding="utf-8")
        return

    fieldnames = list(rows[0].keys())
    for row in rows[1:]:
        for key in row.keys():
            if key not in fieldnames:
                fieldnames.append(key)

    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)


def summarize_render(
    memo_file: Path,
    memo_payload: dict[str, Any],
    docx_path: Path | None,
    pdf_path: Path | None,
    error: str | None = None,
) -> dict[str, Any]:
    context = memo_payload.get("memo_context", {}) or {}
    borrower = context.get("borrower", {}) or {}
    experiment = memo_payload.get("experiment_config", {}) or {}
    runner = memo_payload.get("benchmark_runner", {}) or {}
    requested = runner.get("requested_config", {}) or {}

    return {
        "rendered_at_utc": datetime.now(timezone.utc).isoformat(),
        "memo_file": str(memo_file),
        "symbol": requested.get("symbol") or borrower.get("symbol"),
        "company_name": borrower.get("company_name"),
        "industry": borrower.get("industry"),
        "sector": borrower.get("sector"),
        "country": borrower.get("country"),
        "context_mode": experiment.get("context_mode") or requested.get("context_mode"),
        "policy_mode": experiment.get("policy_mode") or requested.get("policy_mode"),
        "prompt_mode": experiment.get("prompt_mode") or requested.get("prompt_mode"),
        "model_tier": experiment.get("model_tier") or requested.get("model_tier"),
        "model": memo_payload.get("openai_model") or experiment.get("model"),
        "experiment_id": experiment.get("experiment_id"),
        "narrative_source": memo_payload.get("narrative_source"),
        "docx_file": str(docx_path) if docx_path else None,
        "pdf_file": str(pdf_path) if pdf_path else None,
        "error": error,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description="Render stored credit memo payload JSON files to DOCX/PDF.")
    parser.add_argument("--memo-dir", required=True, help="Directory containing stored memo JSON files.")
    parser.add_argument("--output-dir", default=None, help="Defaults to <memo-dir>/../rendered_files.")
    parser.add_argument("--renderer-module", default=None, help="Optional path to credit_memo_documents.py")
    parser.add_argument("--formats", choices=["docx", "pdf", "both"], default="both")
    parser.add_argument("--pattern", default="*.json")
    parser.add_argument("--recursive", action="store_true")
    parser.add_argument("--resume", action="store_true", help="Skip files where requested output already exists.")
    parser.add_argument("--limit", type=int, default=None)
    parser.add_argument("--libreoffice-bin", default=None, help="Optional path to LibreOffice binary.")
    parser.add_argument("--summary-csv", default=None)
    parser.add_argument("--prefix", default="capital_benchmark_credit_memo")

    args = parser.parse_args()

    memo_dir = Path(args.memo_dir)
    if not memo_dir.exists():
        raise FileNotFoundError(f"Memo directory not found: {memo_dir}")

    if args.libreoffice_bin:
        os.environ["LIBREOFFICE_BIN"] = args.libreoffice_bin

    output_dir = Path(args.output_dir) if args.output_dir else memo_dir.parent / "rendered_files"
    docx_dir = output_dir / "docx"
    pdf_dir = output_dir / "pdf"
    summary_csv = Path(args.summary_csv) if args.summary_csv else output_dir / "render_summary.csv"
    errors_jsonl = output_dir / "render_errors.jsonl"

    render_credit_memo_docx, convert_docx_to_pdf = load_renderer(args.renderer_module)

    memo_files = discover_memo_files(memo_dir, args.pattern, recursive=bool(args.recursive))
    if args.limit is not None:
        memo_files = memo_files[: args.limit]

    print(f"Rendering {len(memo_files)} stored memos")
    print(f"Memo directory: {memo_dir}")
    print(f"Output directory: {output_dir}")
    print(f"Formats: {args.formats}")

    rows: list[dict[str, Any]] = []

    for i, memo_file in enumerate(memo_files, start=1):
        try:
            memo_payload = load_memo_payload(memo_file)
            stem = stable_output_stem(memo_file, memo_payload, args.prefix)
            docx_path = docx_dir / f"{stem}.docx"
            pdf_path = pdf_dir / f"{stem}.pdf"

            needs_docx = args.formats in {"docx", "both"} or args.formats == "pdf"
            needs_pdf = args.formats in {"pdf", "both"}

            if args.resume:
                docx_ok = (not needs_docx) or docx_path.exists()
                pdf_ok = (not needs_pdf) or pdf_path.exists()
                if docx_ok and pdf_ok:
                    print(f"[{i}/{len(memo_files)}] {memo_file.name} -> skipped existing")
                    rows.append(summarize_render(memo_file, memo_payload, docx_path if docx_path.exists() else None, pdf_path if pdf_path.exists() else None))
                    continue

            print(f"[{i}/{len(memo_files)}] {memo_file.name} -> rendering")

            rendered_docx: Path | None = None
            rendered_pdf: Path | None = None

            if needs_docx:
                docx_dir.mkdir(parents=True, exist_ok=True)
                rendered_docx = render_credit_memo_docx(memo_payload, docx_path)

            if needs_pdf:
                # PDF conversion needs the DOCX as an intermediate even if the user only requested PDF.
                if rendered_docx is None:
                    docx_dir.mkdir(parents=True, exist_ok=True)
                    rendered_docx = render_credit_memo_docx(memo_payload, docx_path)
                pdf_dir.mkdir(parents=True, exist_ok=True)
                rendered_pdf = convert_docx_to_pdf(rendered_docx, pdf_dir)

            rows.append(summarize_render(memo_file, memo_payload, rendered_docx, rendered_pdf))
            print(f"    docx={rendered_docx} pdf={rendered_pdf}")

        except Exception as exc:
            error = f"{type(exc).__name__}: {exc}"
            print(f"[{i}/{len(memo_files)}] {memo_file.name} -> ERROR: {error}")

            try:
                memo_payload = load_memo_payload(memo_file)
            except Exception:
                memo_payload = {}

            row = summarize_render(memo_file, memo_payload, None, None, error=error)
            rows.append(row)

            errors_jsonl.parent.mkdir(parents=True, exist_ok=True)
            with errors_jsonl.open("a", encoding="utf-8") as handle:
                handle.write(json.dumps(row, ensure_ascii=False) + "\n")

        write_summary_csv(summary_csv, rows)

    write_summary_csv(summary_csv, rows)

    print("Done.")
    print(f"Summary CSV: {summary_csv}")
    print(f"DOCX directory: {docx_dir}")
    print(f"PDF directory: {pdf_dir}")
    if errors_jsonl.exists():
        print(f"Errors JSONL: {errors_jsonl}")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())

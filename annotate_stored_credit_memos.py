#!/usr/bin/env python3
"""
Annotate stored Capital Benchmark credit memos offline.

This script reads memo_payload JSON files previously generated by
run_credit_memo_generation_grid_20_names.py and applies the deterministic
annotation module locally.

No OpenAI calls are made by this script.

Expected input:
    output_dir_from_generation/
      raw_memos/
        *.json

Default output:
    output_dir_from_generation/
      offline_annotations/
      offline_annotation_summary.csv
      offline_annotations.jsonl

Example:
    python annotate_stored_credit_memos.py \
        --memo-dir benchmark_runs/benchmark_20_mini_memos/raw_memos \
        --output-dir benchmark_runs/benchmark_20_mini_memos/offline_annotations

If running outside the production project root, pass the annotation module path:
    python annotate_stored_credit_memos.py \
        --memo-dir benchmark_runs/benchmark_20_mini_memos/raw_memos \
        --annotation-module /opt/capitalbenchmark-api/model/credit_memo_annotation.py
"""

from __future__ import annotations

import argparse
import csv
import importlib.util
import json
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Callable


def write_json(path: Path, payload: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, indent=2, ensure_ascii=False), encoding="utf-8")


def append_jsonl(path: Path, payload: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a", encoding="utf-8") as handle:
        handle.write(json.dumps(payload, ensure_ascii=False) + "\n")


def load_annotator(annotation_module_path: str | None = None) -> Callable[[dict[str, Any]], dict[str, Any]]:
    if annotation_module_path:
        module_path = Path(annotation_module_path)
        if not module_path.exists():
            raise FileNotFoundError(f"Annotation module not found: {module_path}")

        spec = importlib.util.spec_from_file_location("credit_memo_annotation_dynamic", module_path)
        if spec is None or spec.loader is None:
            raise ImportError(f"Could not load module spec from: {module_path}")

        module = importlib.util.module_from_spec(spec)
        sys.modules["credit_memo_annotation_dynamic"] = module
        spec.loader.exec_module(module)

        annotator = getattr(module, "annotate_credit_memo", None)
        if not callable(annotator):
            raise AttributeError(f"{module_path} does not define annotate_credit_memo(memo_payload)")
        return annotator

    try:
        from model.credit_memo_annotation import annotate_credit_memo
        return annotate_credit_memo
    except Exception as exc:
        raise ImportError(
            "Could not import model.credit_memo_annotation.annotate_credit_memo. "
            "Run from the project root or pass --annotation-module /path/to/credit_memo_annotation.py"
        ) from exc


def discover_memo_files(memo_dir: Path, pattern: str, recursive: bool) -> list[Path]:
    if recursive:
        return sorted(memo_dir.rglob(pattern))
    return sorted(memo_dir.glob(pattern))


def summarize_annotation(annotation: dict[str, Any], memo_payload: dict[str, Any], memo_file: Path, annotation_file: Path) -> dict[str, Any]:
    metadata = annotation.get("benchmark_metadata", {}) or {}
    scores = annotation.get("scores", {}) or {}
    diagnostics = annotation.get("diagnostics", {}) or {}
    policy_diag = diagnostics.get("policy_detection", {}) or {}
    missing_diag = diagnostics.get("missing_information", {}) or {}
    unsupported_diag = diagnostics.get("unsupported_claims", {}) or {}

    runner = memo_payload.get("benchmark_runner", {}) or {}
    requested = runner.get("requested_config", {}) or {}
    experiment_config = memo_payload.get("experiment_config", {}) or {}
    memo_context = memo_payload.get("memo_context", {}) or {}
    borrower = memo_context.get("borrower", {}) or {}

    annotations = annotation.get("annotations", []) or []
    category_counts: dict[str, int] = {}
    severity_counts: dict[str, int] = {}
    for item in annotations:
        category = str(item.get("category") or "unknown")
        severity = str(item.get("severity") or "unknown")
        category_counts[category] = category_counts.get(category, 0) + 1
        severity_counts[severity] = severity_counts.get(severity, 0) + 1

    return {
        "generated_at_utc": annotation.get("generated_at_utc"),
        "memo_file": str(memo_file),
        "annotation_file": str(annotation_file),
        "symbol": requested.get("symbol") or borrower.get("symbol"),
        "company_name": borrower.get("company_name"),
        "industry": borrower.get("industry"),
        "sector": borrower.get("sector"),
        "country": borrower.get("country"),
        "context_mode": metadata.get("context_mode") or experiment_config.get("context_mode") or requested.get("context_mode"),
        "policy_mode": metadata.get("policy_mode") or experiment_config.get("policy_mode") or requested.get("policy_mode"),
        "prompt_mode": metadata.get("prompt_mode") or experiment_config.get("prompt_mode") or requested.get("prompt_mode"),
        "model_tier": metadata.get("model_tier") or experiment_config.get("model_tier") or requested.get("model_tier"),
        "model": metadata.get("model") or memo_payload.get("openai_model") or experiment_config.get("model"),
        "run_id": requested.get("run_id"),
        "experiment_id": metadata.get("experiment_id") or experiment_config.get("experiment_id"),
        "narrative_source": metadata.get("narrative_source") or memo_payload.get("narrative_source"),
        "overall_score": scores.get("overall_score"),
        "policy_detection_score": scores.get("policy_detection_score"),
        "missing_information_detection_score": scores.get("missing_information_detection_score"),
        "annotation_count": scores.get("annotation_count"),
        "critical_or_high_issue_count": scores.get("critical_or_high_issue_count"),
        "factual_error_count": scores.get("factual_error_count"),
        "unsupported_claim_count": scores.get("unsupported_claim_count"),
        "expected_policy_ids": ",".join(policy_diag.get("expected_policy_ids", []) or []),
        "observed_policy_ids": ",".join(policy_diag.get("observed_policy_ids", []) or []),
        "missed_policy_ids": ",".join(policy_diag.get("missed_policy_ids", []) or []),
        "additional_policy_ids": ",".join(policy_diag.get("additional_policy_ids", []) or []),
        "expected_missing_information": ",".join(missing_diag.get("expected_missing_information", []) or []),
        "found_missing_information": ",".join(missing_diag.get("found_missing_information", []) or []),
        "missed_missing_information": ",".join(missing_diag.get("missed_missing_information", []) or []),
        "potential_unsupported_phrases": ",".join(unsupported_diag.get("potential_unsupported_phrases", []) or []),
        "category_counts_json": json.dumps(category_counts, sort_keys=True),
        "severity_counts_json": json.dumps(severity_counts, sort_keys=True),
        "error": None,
    }


def write_summary_csv(path: Path, rows: list[dict[str, Any]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)

    if not rows:
        path.write_text("", encoding="utf-8")
        return

    fieldnames = list(rows[0].keys())
    for row in rows[1:]:
        for key in row.keys():
            if key not in fieldnames:
                fieldnames.append(key)

    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)


def main() -> int:
    parser = argparse.ArgumentParser(description="Run deterministic annotations against stored memo payloads.")
    parser.add_argument("--memo-dir", required=True, help="Directory containing stored memo_payload JSON files.")
    parser.add_argument("--output-dir", default=None, help="Directory for annotation JSON files. Defaults to <memo-dir>/../offline_annotations.")
    parser.add_argument("--summary-csv", default=None, help="Summary CSV path. Defaults to <output-parent>/offline_annotation_summary.csv.")
    parser.add_argument("--jsonl", default=None, help="JSONL output path. Defaults to <output-parent>/offline_annotations.jsonl.")
    parser.add_argument("--pattern", default="*.json")
    parser.add_argument("--recursive", action="store_true")
    parser.add_argument("--annotation-module", default=None, help="Optional path to credit_memo_annotation.py")
    parser.add_argument("--resume", action="store_true", help="Skip annotation files that already exist.")
    parser.add_argument("--limit", type=int, default=None)
    parser.add_argument("--include-memo-payload", action="store_true", help="Also embed memo_payload in each annotation JSON. Usually leave off.")

    args = parser.parse_args()

    memo_dir = Path(args.memo_dir)
    if not memo_dir.exists():
        raise FileNotFoundError(f"Memo directory not found: {memo_dir}")

    output_dir = Path(args.output_dir) if args.output_dir else memo_dir.parent / "offline_annotations"
    summary_csv = Path(args.summary_csv) if args.summary_csv else output_dir.parent / "offline_annotation_summary.csv"
    jsonl_path = Path(args.jsonl) if args.jsonl else output_dir.parent / "offline_annotations.jsonl"
    errors_path = output_dir.parent / "offline_annotation_errors.jsonl"

    annotate_credit_memo = load_annotator(args.annotation_module)

    memo_files = discover_memo_files(memo_dir, args.pattern, recursive=bool(args.recursive))
    if args.limit is not None:
        memo_files = memo_files[: args.limit]

    print(f"Annotating {len(memo_files)} stored memos")
    print(f"Memo directory: {memo_dir}")
    print(f"Output directory: {output_dir}")

    summary_rows: list[dict[str, Any]] = []

    for i, memo_file in enumerate(memo_files, start=1):
        annotation_file = output_dir / memo_file.name.replace(".json", "__annotation.json")
        label = f"[{i}/{len(memo_files)}] {memo_file.name}"

        try:
            if args.resume and annotation_file.exists():
                annotation = json.loads(annotation_file.read_text(encoding="utf-8"))
                memo_payload = json.loads(memo_file.read_text(encoding="utf-8"))
                print(f"{label} -> skipped existing")
            else:
                memo_payload = json.loads(memo_file.read_text(encoding="utf-8"))
                annotation = annotate_credit_memo(memo_payload)

                annotation.setdefault("offline_annotation_runner", {})
                annotation["offline_annotation_runner"].update({
                    "memo_file": str(memo_file),
                    "annotation_file": str(annotation_file),
                    "annotated_at_utc": datetime.now(timezone.utc).isoformat(),
                    "source": "stored_memo_payload",
                    "llm_calls_made": 0,
                })

                if args.include_memo_payload:
                    annotation["memo_payload"] = memo_payload

                write_json(annotation_file, annotation)
                append_jsonl(jsonl_path, annotation)

            row = summarize_annotation(annotation, memo_payload, memo_file, annotation_file)
            summary_rows.append(row)

            print(
                f"{label} -> overall={row.get('overall_score')} "
                f"policy={row.get('policy_detection_score')} "
                f"missing={row.get('missing_information_detection_score')} "
                f"annotations={row.get('annotation_count')}"
            )

        except Exception as exc:
            error_record = {
                "error_at_utc": datetime.now(timezone.utc).isoformat(),
                "memo_file": str(memo_file),
                "annotation_file": str(annotation_file),
                "error_type": type(exc).__name__,
                "error": str(exc),
            }
            append_jsonl(errors_path, error_record)

            summary_rows.append({
                "generated_at_utc": datetime.now(timezone.utc).isoformat(),
                "memo_file": str(memo_file),
                "annotation_file": str(annotation_file),
                "symbol": None,
                "company_name": None,
                "industry": None,
                "sector": None,
                "country": None,
                "context_mode": None,
                "policy_mode": None,
                "prompt_mode": None,
                "model_tier": None,
                "model": None,
                "run_id": None,
                "experiment_id": None,
                "narrative_source": None,
                "overall_score": None,
                "policy_detection_score": None,
                "missing_information_detection_score": None,
                "annotation_count": None,
                "critical_or_high_issue_count": None,
                "factual_error_count": None,
                "unsupported_claim_count": None,
                "expected_policy_ids": None,
                "observed_policy_ids": None,
                "missed_policy_ids": None,
                "additional_policy_ids": None,
                "expected_missing_information": None,
                "found_missing_information": None,
                "missed_missing_information": None,
                "potential_unsupported_phrases": None,
                "category_counts_json": None,
                "severity_counts_json": None,
                "error": f"{type(exc).__name__}: {exc}",
            })
            print(f"{label} -> ERROR: {type(exc).__name__}: {exc}")

        write_summary_csv(summary_csv, summary_rows)

    write_summary_csv(summary_csv, summary_rows)

    print("Done.")
    print(f"Summary CSV: {summary_csv}")
    print(f"Annotations JSONL: {jsonl_path}")
    print(f"Annotation files: {output_dir}")
    if errors_path.exists():
        print(f"Errors JSONL: {errors_path}")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
